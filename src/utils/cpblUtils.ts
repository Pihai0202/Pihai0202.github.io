/**
 * 依據選手帳號 ID (Acnt) 或原始名稱反查選手姓名
 */
export const resolveCpblPlayerName = (name?: string, acnt?: string | number): string => {
  if (name && name.trim()) {
    const clean = name.trim().replace(/\u200B/g, '')
    // 若名稱不是純數字或預設標籤，直接回傳
    if (!/^\d+$/.test(clean) && clean !== '未登錄' && clean !== '待公告') {
      return clean
    }
  }

  if (!acnt) return name?.trim() || ''

  const strAcnt = String(acnt).trim()
  if (!strAcnt) return name?.trim() || ''

  // 1. 直接比對
  if (CPBL_PLAYER_MAP[strAcnt]) return CPBL_PLAYER_MAP[strAcnt]

  // 2. 補滿 10 碼 0
  const padded = strAcnt.padStart(10, '0')
  if (CPBL_PLAYER_MAP[padded]) return CPBL_PLAYER_MAP[padded]

  // 3. 去除前綴 0
  const stripped = strAcnt.replace(/^0+/, '')
  if (CPBL_PLAYER_MAP[stripped]) return CPBL_PLAYER_MAP[stripped]

  return name?.trim() || ''
}

